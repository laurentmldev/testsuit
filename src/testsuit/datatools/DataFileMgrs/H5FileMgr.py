def GetH5FileType(fileName: str, h5File: h5py.File | None=None) -> str:
    if not h5File:
        h5File=h5py.File(fileName, 'r')

    # Dewesoft files
    if "File name" in h5File.attrs and \
        (h5File.attrs["File name"].lower().endswith("dxd") or h5File.attrs["File name"].lower().endswith("d7d")):
        return "Dewesoft"

    # Files generated by Channels tools
    for name, h5obj in h5File.items():
        if isinstance(h5obj,h5py.Group) and name=="channels":
            return "channels" 
            
    # Files generated by functional simulation
    for name, h5obj in h5File.items():
        if isinstance(h5obj,h5py.Group) and "LOG_SENS" in h5obj:
            return "FES"     
       
    return "Generic"

