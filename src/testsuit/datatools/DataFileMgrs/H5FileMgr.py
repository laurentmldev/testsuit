class H5FileMgrDewesoft(H5FileMgr):

    def __init__(self,
             filename: str,
             fileIdx: int = 0) -> None:
        super().__init__(filename,fileIdx)
        startDateStr=self.getH5FileRoot().attrs["Start store time"].strip()
        get_logger().debug("H5 Dewesoft File - "+startDateStr+" - "+self.getBaseName())
        
    def getFileInfo(self):
        fileInfo=super().getFileInfo()

        return fileInfo+["H5-Type: Dewesoft",
                    "Sample rate:"+str(self.getH5FileRoot().attrs["Sample rate"])+" Hz",
                    "Start:"+str(self.getH5FileRoot().attrs["Start store time"].strip()),
                    "End:"+str(self.getH5FileRoot().attrs["End store time"].strip())]
    
    def finalizeH5Dataframe(self,
                        paramName: str,
                        dfParam: pd.DataFrame,
                        h5ParamDataset: h5py.Dataset,
                        monitorProgress: MonitorProgress | None = None) -> pd.DataFrame:
                        
        columnsDesc=h5ParamDataset.attrs["Column Description"]
        pattern = re.compile(r'Column \d+:\s+(\S+)')
        colNames=pattern.findall(columnsDesc)
        colsNames={}
        colIdx=0
        timeColIdx=None
        for colName in colNames:
            if colName=="Data":
                colName=paramName
            if colName=="Time":
                timeColIdx=colIdx
            
            colsNames[colIdx]=colName
            colIdx+=1        
        
        # asynchronous data (has a "Time" column)
        # or brute force dataframe with time column but wrong header info ... (yes it happened)
        if timeColIdx is not None \
            or len(h5ParamDataset.shape)==2 and h5ParamDataset.shape[1]==2 and len(colNames)==1:
            dfParam.set_index(dfParam.columns[0],inplace=True)
            dfParam.index.name="Time"
            dfParam.index=dfParam.index.astype('float64') # float64 needed for sufficient precision 
        else:
            acquisitionRate=float(h5ParamDataset.attrs["Acquisition Rate"])
            periodSec=1.0/acquisitionRate
            dfParam.index=pd.Index(np.arange(0,dfParam.index.size*periodSec,periodSec,dtype="float64"))
            dfParam.index.name="Time"

        # offset timestamps if dates are relatives (file shall be exported with relative timestamps)
        # /!\ timestamps are based on "Start store time", not "Start time"
        startDateStr=self.getH5FileRoot().attrs["Start store time"].strip()
        startDate=datetime.strptime(startDateStr, '%d/%m/%Y %H:%M:%S').replace(tzinfo=timezone.utc)
        dfParam.index+=startDate.timestamp()
        
        dfParam.name=paramName
        dfParam.rename(columns={dfParam.columns[0]:paramName},inplace=True)  
        
        return dfParam
        
