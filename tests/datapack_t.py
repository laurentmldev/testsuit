def test_datapack_nominal(tmp_path, no_git):
    zip_path = datapack(TESTDEF, nocheck=True, output_dir=tmp_path)
    assert zip_path.parent == tmp_path and zip_path.name.startswith("my_test_def_my_setup_") and zip_path.stem.endswith("_DRAFT")

    work = TESTDEF.parent / ".current_datapack"
    inputs = work / "data" / "mycmp1" / "input"
    assert (inputs / "MyRef1.txt").read_text() == (
        "# generated by datapack for My Test Def\n\n"
        "This is a sample ref File: 3.1415 m3/s\n"
        "for Comp One (mycmp1) on test platform by TOYTRAIN\n"
        "sensors: s1 s2 s3\n")
    # the second slot gets its own values
    assert "for Comp Two (mycmp2)" in (work / "data" / "mycmp2" / "input" / "MyRef1.txt").read_text()
    # copy: not rendered
    assert (inputs / "MyRef2.txt").read_text() == "copied as is: {{ not_a_key }}\n"
    # folder, rendered file by file; a value referencing another key
    assert yaml.safe_load((inputs / "conf" / "limits.yml").read_text()) == \
        {"param2": {"min": 0.1, "value": 5, "max": 0.3, "unit": "m3/s"}}
    # glob: always a folder
    assert (inputs / "local" / "my_ref_file.txt").is_file()
    # optional input not found: skipped
    assert not (inputs / "missing.txt").exists()
    # postprocess
    assert "This is a replaced ref File" in (inputs / "replaced.txt").read_text()
    assert (work / "data" / "mycmp1" / "output").is_dir()

    manifest = yaml.safe_load((work / "datapack.yml").read_text())
    assert manifest["testdef"]["id"] == "my_test_def" and manifest["setup"]["name"] == "Setup for My Test Def"
    assert manifest["nocheck"] is True
    keys = manifest["slots"]["mycmp1"]["inputs"][0]["keys"]["MyRef1.txt"]
    assert keys["platform.name"].endswith("testdef/overrides.yml")
    assert keys["platform.vendor"].endswith("setup/globals.yml")
    assert manifest["slots"]["mycmp1"]["inputs"][2]["keys"]["conf/limits.yml"]["my_dataset.param2.value"].endswith("values.yml")

    context = yaml.safe_load((work / "context.yml").read_text())
    assert context["value"]["sensors"] == ["s1", "s2", "s3"]
    assert context["my_dataset"]["param2"]["metadata"]["rawUnit"] == "m3/s"
    assert context["datapack"]["name"] == zip_path.stem

    # definition kept as written, pipeline included
    testdef = yaml.safe_load((work / "definition" / "testdef.yml").read_text())
    assert testdef["pipeline"]["phases"][0]["steps"][0]["run"] == "scp {{ slot.id }}"
    assert (work / "definition" / "dictionaries" / "setup" / "globals.yml").is_file()
    assert (work / "definition" / "dictionaries" / "testdef" / "values.yml").is_file()

    with zipfile.ZipFile(zip_path) as archive:
        names = archive.namelist()
    root = zip_path.stem
    for name in ("bagit.txt", "bag-info.txt", "manifest-sha256.txt", "tagmanifest-sha256.txt", "datapack.yml",
                 "context.yml", "data/mycmp1/input/MyRef1.txt", "data/mycmp1/output/"):
        assert f"{root}/{name}" in names
    assert verify_datapack(zip_path) == []


def test_verify_detects_changes(tmp_path, no_git):
    zip_path = datapack(TESTDEF, nocheck=True, output_dir=tmp_path / "out")
    tampered = tmp_path / "tampered.zip"
    with zipfile.ZipFile(zip_path) as src, zipfile.ZipFile(tampered, "w") as dst:
        for item in src.infolist():
            data = src.read(item)
            if item.filename.endswith("data/mycmp1/input/MyRef1.txt"):
                data += b"changed"
            dst.writestr(item, data)
        dst.writestr(f"{zip_path.stem}/data/extra.txt", "x")
    assert sorted(verify_datapack(tampered)) == ["checksum mismatch: data/mycmp1/input/MyRef1.txt",
                                                 "file not in manifest: data/extra.txt"]


