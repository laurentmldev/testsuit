def test_output_dir_from_dictionary(etc_copy, no_git):
    _edit(etc_copy / "setup" / "globals.yml", "/../../../tmp/datapacks", "/../out")
    zip_path = datapack(etc_copy / "testdef" / "datapack_utest.yml", nocheck=True)
    assert zip_path.parent == (etc_copy / "out").resolve()


def _edit(path, old, new):
    text = path.read_text()
    assert old in text
    path.write_text(text.replace(old, new))


@pytest.mark.parametrize("file,old,new,error", [
    ("setup/utest_ref_files/ref1.txt", "{{ platform.vendor }}", "{{ platform.nope }}", "'dict object' has no attribute 'nope'|nope"),
    ("testdef/values.yml", "beta: Hello world", "beta: \"{{ value.gamma }}\"\n  gamma: \"{{ value.beta }}\"", "circular reference"),
    ("setup/utest_setup.yml", "source: utest_ref_files/ref2.txt", "source: utest_ref_files/nope.txt", "input 'utest_ref_files/nope.txt' not found"),
    ("testdef/datapack_utest.yml", "setup_config: nominal", "setup_config: unknown", "no configuration 'unknown'"),
    ("setup/utest_setup.yml", "type: comp1, configuration: standard}\n  other", "type: comp1, configuration: nope}\n  other", "no configuration 'nope' for type 'comp1'"),
    ("setup/utest_setup.yml", "            method: copy\n          - source: utest_ref_files/conf_dir", "            methd: copy\n          - source: utest_ref_files/conf_dir", "methd"),
    ("testdef/datapack_utest.yml", "  - overrides.yml", "  - nope.yml", "testdef dictionary not reachable"),
    ("setup/utest_setup.yml", "replace s/sample/replaced/g", "nope", "unknown processor 'nope'"),
])
def test_errors(etc_copy, tmp_path, no_git, file, old, new, error):
    _edit(etc_copy / file, old, new)
    with pytest.raises(DatapackError, match=error):
        datapack(etc_copy / "testdef" / "datapack_utest.yml", nocheck=True, output_dir=tmp_path / "out")


def test_cli_verify(tmp_path, no_git, monkeypatch, capsys):
    from testsuit.cli import datapack as cli
    zip_path = datapack(TESTDEF, nocheck=True, output_dir=tmp_path)
    monkeypatch.setattr("sys.argv", ["datapack", "--verify", str(zip_path)])
